export const slideById = (id) => SLIDES.find((s) => s.id === id);

/** Порядок кадров: сначала перечисленные в `first`, затем остальные по умолчанию. */
export function orderSlides(first = []) {
  const head = first.map(slideById).filter(Boolean);
  const rest = SLIDES.filter((s) => !first.includes(s.id));
  return [...head, ...rest];
}
